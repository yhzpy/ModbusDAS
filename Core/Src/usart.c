void MX_USART2_UART_Init(void)
{

  /* USER CODE BEGIN USART2_Init 0 */

  /* USER CODE END USART2_Init 0 */

  /* USER CODE BEGIN USART2_Init 1 */

  /* USER CODE END USART2_Init 1 */
  huart2.Instance = USART2;
  huart2.Init.BaudRate = 115200;
  huart2.Init.WordLength = UART_WORDLENGTH_8B;
  huart2.Init.StopBits = UART_STOPBITS_1;//停止位设为 1 位。串口一帧数据发送完后会有一个空闲电平作为帧结束标志
  huart2.Init.Parity = UART_PARITY_NONE;//不使用奇偶校验位 奇偶校验就是在 8 位数据之后额外附加 1 个 bit，用来检查数据在传输中是否出错
  //偶校验（Even）：保证"数据位 + 校验位"中 1 的总个数为偶数
  //奇校验（Odd）：保证"数据位 + 校验位"中 1 的总个数为奇数
  huart2.Init.Mode = UART_MODE_TX_RX;//串口工作模式为全双工
  huart2.Init.HwFlowCtl = UART_HWCONTROL_NONE;//硬件流控
  //STM32 的硬件流控用两根额外的引脚：RTS（请求发送） 和 CTS（允许发送）：
  //B 忙不过来时，把 RTS 拉高 → A 的 CTS 检测到高电平 → A 暂停发送
  //B 处理完了，RTS 拉低 → A 收到"绿灯"，继续发送
  //rs485没更多线 所以不用
  huart2.Init.OverSampling = UART_OVERSAMPLING_16;//过采样
  //串口是异步通信——收发双方没有共享时钟线，
  //接收方只能靠事先约定的波特率去"猜"每个 bit 什么时候开始、什么时候结束。
  //而双方的晶振频率总有微小偏差，猜得越粗越容易出错。 接收端用一个比波特率高 N 倍的时钟去采样
  if (HAL_UART_Init(&huart2) != HAL_OK)
  {
    Error_Handler();
  }
  /* USER CODE BEGIN USART2_Init 2 */
  /* USER CODE END USART2_Init 2 */

}

